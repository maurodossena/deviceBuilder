"""Export of a device to the formats read by QUATREX and OMEN."""

import os

import numpy as np
from scipy import sparse as sp

from .base import DeviceBase
from .io import print_bin


class ExportMixin(DeviceBase):
    """Writers for the input decks of the transport codes."""

    def export_data_QUATREX(
        self,
        transport_dir=[0],
        output_dir="device",
        cont="lr",
        export_bonds=False,
    ):
        """
        Export the device data to a specified directory in the QUATREX format.

        Parameters:
        -----------
        transport_dir : list
            List of directions along which transport occurs (0 for x, 1 for y, 2 for z).
        output_dir : str
            Directory where the device data will be saved.
        cont : str
            Contacts to be exported. Can be "l", "r", "t", "b", or any combination of these letters.
        export_bonds : bool
            Whether to export bond data.
        """

        # TODO: `export_bonds` is accepted but never used.

        import toml
        from qttools.utils.hdf5_utils import save_hdf5_dict

        # Create the output directory if it doesn't exist
        input_dir = os.path.join(output_dir, "inputs")
        os.makedirs(input_dir, exist_ok=True)

        # Save Hamiltonian and Overlap matrices
        save_hdf5_dict(
            os.path.join(input_dir, "hamiltonian.h5"),
            self._blocks_to_save(self.H, transport_dir),
        )
        save_hdf5_dict(
            os.path.join(input_dir, "overlap.h5"),
            self._blocks_to_save(self.S, transport_dir),
        )

        # Create potential.npy if potential is defined
        if self.potential is not None:
            np.save(os.path.join(input_dir, "potential.npy"), self.potential)

        # Crate lattice.xyz
        xyz_path = os.path.join(input_dir, "structure.xyz")
        with open(xyz_path, "w") as f:
            f.write(f"{len(self.lattice['at'])}\n")  # first line: number of atoms
            lattice_vals = " ".join(f"{val:.6f}" for val in self.lattice["L"].flatten())
            f.write(f'Lattice="{lattice_vals}"\n')
            for at_type, (x, y, z) in zip(self.lattice["at"], self.lattice["coords"]):
                f.write(f"{at_type} {x:.6f} {y:.6f} {z:.6f}\n")

        # Create config.toml
        config = self._build_quatrex_config(transport_dir, cont)

        with open(os.path.join(output_dir, "config.toml"), "w") as f:
            f.write(
                "# This file was generated by deviceBuilder. https://github.com/maurodossena/deviceBuilder.git\n"
            )
            toml.dump(config, f)

    def _blocks_to_save(self, M: dict, transport_dir: list) -> dict:
        """
        Collect the upper triangle of every block that is not a coupling along a
        transport direction, keyed by the string form of its cell index.

        Parameters:
        -----------
        M : dict
            Hamiltonian or Overlap dictionary.
        transport_dir : list
            List of directions along which transport occurs.
        Returns:
        --------
        dict
            The blocks to be written to disk.
        """

        to_save = {}
        for key, value in M.items():
            # Don't save the coupling matrices in the transport directions
            if any(key[dir] != 0 for dir in transport_dir):
                continue

            if not value.has_canonical_format:
                raise Exception("Matrix is not in canonical format")
            if not isinstance(value, sp.csr_matrix):
                raise Exception("Matrix is not in csr format")
            to_save[str(list(key))] = sp.triu(value)

        return to_save

    def _contact_lattice_vector(self, axis: int, side: str) -> np.ndarray:
        """
        Find the periodicity vector of a contact.

        It looks for the atom that is furthest along `axis`, and returns the
        vector to the closest atom that is aligned with it along the other two
        directions.

        Parameters:
        -----------
        axis : int
            Direction the contact is periodic along (0 for x, 1 for y).
        side : str
            Which end of the device the contact sits at, "min" or "max".
        Returns:
        --------
        np.ndarray
            The contact lattice vector, in Cartesian coordinates.
        """

        coords = self.lattice["coords"]
        other_dirs = [i for i in range(3) if i != axis]

        edge_at = np.argmin(coords[:, axis]) if side == "min" else np.argmax(coords[:, axis])

        # Fractional distance of every atom from the edge atom
        delta = (coords - coords[edge_at, :]) @ np.linalg.inv(self.lattice["L"])

        # Keep the atoms aligned with the edge atom, excluding the atom itself
        delta = delta[abs(delta[:, other_dirs[0]]) < 1e-3, :]
        delta = delta[abs(delta[:, other_dirs[1]]) < 1e-3, :]
        delta = delta[abs(delta[:, axis]) > 1e-5, :]

        # TODO: the closest atom is selected on the x component, also for the
        # top/bottom contacts, where it should probably be `axis`. After the
        # filtering above every remaining row has an x component close to zero
        # for those contacts, so the pick is essentially arbitrary. Kept as is
        # to preserve the original behaviour.
        closest = delta[np.argmin(abs(delta[:, 0])), :]

        return np.round(closest @ self.lattice["L"], decimals=3)

    def _build_quatrex_config(self, transport_dir: list, cont: str) -> dict:
        """
        Build the dictionary written out as `config.toml`.

        Parameters:
        -----------
        transport_dir : list
            List of directions along which transport occurs.
        cont : str
            Contacts to be exported ("l", "r", "t", "b", or any combination).
        Returns:
        --------
        dict
            The QUATREX configuration.
        """

        config = {}
        config["simulation_dir"] = "."
        config["formalism"] = "wf"

        config["qtbm"] = {}
        config["qtbm"]["max_batch_size"] = 1
        config["qtbm"]["low_rank_obc"] = False

        config["device"] = {}
        config["device"]["transport_direction"] = ["x", "y", "z"][transport_dir[0]]
        config["device"]["num_orbitals_per_atom"] = self.orb_map
        config["device"]["kpoint_grid"] = [1, 1, 1]
        config["device"]["kpoint_shift"] = [0, 0, 0]

        lattice_round = np.round(self.lattice["L"], decimals=3)
        coord_round = np.round(self.lattice["coords"], decimals=3)
        lo = [float(np.min(coord_round[:, i]) - 0.01) for i in range(3)]
        hi = [float(np.max(coord_round[:, i]) + 0.01) for i in range(3)]

        cont_list = []
        if "l" in cont:
            latt_vec_l = self._contact_lattice_vector(axis=0, side="min")
            cont_list.append(
                self._contact_entry(
                    name="left",
                    origin=lo,
                    lattice_vectors=[
                        latt_vec_l.tolist(),
                        lattice_round[1, :].tolist(),
                        lattice_round[2, :].tolist(),
                    ],
                    direction="a",
                )
            )

        if "r" in cont:
            latt_vec_r = self._contact_lattice_vector(axis=0, side="max")
            cont_list.append(
                self._contact_entry(
                    name="right",
                    origin=[hi[0], lo[1], lo[2]],
                    lattice_vectors=[
                        latt_vec_r.tolist(),
                        lattice_round[1, :].tolist(),
                        lattice_round[2, :].tolist(),
                    ],
                    direction="a",
                )
            )

        if "t" in cont:
            latt_vec_t = self._contact_lattice_vector(axis=1, side="max")
            cont_list.append(
                self._contact_entry(
                    name="top",
                    origin=[lo[0], hi[1], lo[2]],
                    lattice_vectors=[
                        lattice_round[0, :].tolist(),
                        latt_vec_t.tolist(),
                        lattice_round[2, :].tolist(),
                    ],
                    direction="b",
                )
            )

        if "b" in cont:
            latt_vec_b = self._contact_lattice_vector(axis=1, side="min")
            cont_list.append(
                self._contact_entry(
                    # TODO: the z component of the origin is the maximum, while
                    # the bottom contact sits at the minimum of y. The other
                    # three contacts only use `hi` on the axis they sit at, so
                    # this is likely a copy-paste of the "top" entry and should
                    # be `lo[2]`. Kept as is to preserve the original behaviour.
                    name="bottom",
                    origin=[lo[0], lo[1], hi[2]],
                    lattice_vectors=[
                        lattice_round[0, :].tolist(),
                        latt_vec_b.tolist(),
                        lattice_round[2, :].tolist(),
                    ],
                    direction="b",
                )
            )

        config["device"]["contacts"] = cont_list

        config["electron"] = {}
        config["electron"]["solver"] = {"direct_solver": "thomas"}
        config["electron"]["energy_window_min"] = self.Fermi - 1
        config["electron"]["energy_window_max"] = self.Fermi + 1
        config["electron"]["energy_window_num"] = 201

        config["electron"]["obc"] = {}
        config["electron"]["obc"]["algorithm"] = "spectral"
        config["electron"]["obc"]["num_ref_iterations"] = 4
        config["electron"]["obc"]["nevp_solver"] = "full"
        config["electron"]["obc"]["r_o"] = 1000
        config["electron"]["obc"]["r_i"] = 0.9
        config["electron"]["obc"]["m_0"] = 100
        config["electron"]["obc"]["num_quad_points"] = 64
        config["electron"]["obc"]["min_decay"] = 1e-8
        config["electron"]["obc"]["max_decay"] = 2

        config["compute"] = {"nevp": {"eig_compute_location": "cupy"}}

        return config

    def _contact_entry(
        self, name: str, origin: list, lattice_vectors: list, direction: str
    ) -> dict:
        """
        Assemble the `config.toml` entry of a single contact.

        Parameters:
        -----------
        name : str
            Name of the contact.
        origin : list
            Origin of the contact unit cell.
        lattice_vectors : list
            The three lattice vectors of the contact unit cell.
        direction : str
            Periodicity direction of the contact, "a" or "b".
        Returns:
        --------
        dict
            The contact entry.
        """

        return {
            "name": name,
            "origin": origin,
            "lattice_vectors": lattice_vectors,
            "fermi_level": self.Fermi,
            "direction": direction,
            "temperature": 300,
        }

    def export_data_OMEN(self, output_dir="device_OMEN"):
        """
        Export the device data to a specified directory in the OMEN format.

        Parameters:
        -----------
        output_dir : str
            Directory where the device data will be saved.
        """

        print("In OMEN transport direction is always x (0)")
        # Create the output directory if it doesn't exist
        os.makedirs(output_dir, exist_ok=True)

        # Save Hamiltonian and Overlap matrices
        print_bin(output_dir + "/H_4.bin", self.H[(0, 0, 0)].tocoo())
        if (self.S[(0, 0, 0)] != sp.eye(self.S[(0, 0, 0)].shape[0]).tocsr()).nnz != 0:
            print_bin(output_dir + "/S_4.bin", self.S[(0, 0, 0)].tocoo())

        if (0, 1, 0) in self.H.keys():
            print_bin(output_dir + "/H_5.bin", self.H[(0, 1, 0)].tocoo())
            print_bin(output_dir + "/H_3.bin", self.H[(0, -1, 0)].tocoo())
            if (0, 1, 0) in self.S.keys():
                print_bin(output_dir + "/S_5.bin", self.S[(0, 1, 0)].tocoo())
            if (0, -1, 0) in self.S.keys():
                print_bin(output_dir + "/S_3.bin", self.S[(0, -1, 0)].tocoo())

        # Create potential.npy if potential is defined
        if self.potential is not None:
            with open(os.path.join(output_dir, "vact_dat"), "w") as f:
                for val in self.potential:
                    f.write(f"{val:.6f}  ")

        # Crate lattice.xyz
        xyz_path = os.path.join(output_dir, "lattice_dat")
        swapped_ind = np.array([0, 2, 1])  # OMEN uses x,z,y
        with open(xyz_path, "w") as f:
            f.write(
                f"{len(self.lattice['at'])} 2 0 0 0\n\n"
            )  # first line: number of atoms
            f.write("  ".join(map(str, self.lattice["L"][0, swapped_ind])) + "\n")
            f.write("  ".join(map(str, self.lattice["L"][2, swapped_ind])) + "\n")
            f.write("  ".join(map(str, self.lattice["L"][1, swapped_ind])) + "\n\n")
            for at_type, (x, y, z) in zip(self.lattice["at"], self.lattice["coords"]):
                f.write(f"{at_type}\t{x:.6f}\t{z:.6f}\t{y:.6f}\n")
